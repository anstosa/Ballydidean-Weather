// exercise the installed cli against one prepared exact frozen restore fixture
test("I-IDX-07 installed restore wrapper binds, reconciles, and cleans only owned candidates", {
  skip: restoreScenarioPath === undefined ? "set WEATHER_PAGE_INDEX_RESTORE_E2E_SCENARIO" : false,
  timeout: 900_000,
}, async () => {
  const scenario = JSON.parse(await readFile(restoreScenarioPath, "utf8"));
  assert.equal(scenario.schema, "weather-page-index-restore-scenario/v2");
  assert.equal(scenario.fixtureOnly, true);
  assert.equal(scenario.performanceQualification, false);

  // run one installed wrapper command
  async function runWrapper(mode, config) {
    return runCommand(process.execPath, [
      "--max-old-space-size=64",
      scenario.helper,
      mode,
      "--config",
      config,
      "--admission",
      scenario.admission,
      "--restore-context",
      scenario.context,
    ], { allowFailure: true, timeoutMilliseconds: 180_000 });
  }

  // count private-prefix candidates without trusting wrapper output
  async function candidateCount() {
    const result = await runCommand("docker", [
      "exec",
      scenario.postgresContainer,
      "psql",
      "-U",
      "postgres",
      "-d",
      scenario.fixtureDatabase,
      "-Atc",
      `SELECT count(*) FROM pg_database WHERE datname LIKE '${scenario.fixtureDatabase}_verify_%'`,
    ]);
    return Number(result.stdout.trim());
  }

  const missing = await runWrapper("verify-restore", scenario.noIndexConfig);
  assert.notEqual(missing.code, 0);
  assert.match(missing.stderr, /target.*absent|index is absent/u);
  assert.equal(await candidateCount(), 0);

  const reconciled = await runWrapper("reconcile-restore", scenario.noIndexConfig);
  assert.equal(reconciled.code, 0, reconciled.stderr);
  assert.equal(JSON.parse(reconciled.stdout).result.status, "passed");
  assert.equal(await candidateCount(), 0);

  const verified = await runWrapper("verify-restore", scenario.indexedConfig);
  assert.equal(verified.code, 0, verified.stderr);
  assert.equal(JSON.parse(verified.stdout).result.status, "passed");
  assert.equal(await candidateCount(), 0);

  const intermediate = await runWrapper("verify-restore", scenario.intermediateConfig);
  assert.notEqual(intermediate.code, 0);
  assert.match(intermediate.stderr, /predecessor.*absent|inventory state differs/u);
  assert.equal(await candidateCount(), 0);

  const failedChild = await runWrapper("verify-restore", scenario.badArchiveConfig);
  assert.notEqual(failedChild.code, 0);
  assert.match(failedChild.stderr, /legacy restore failed with exit 1/u);
  assert.equal(await candidateCount(), 0);

  await runCommand("docker", ["exec", scenario.postgresContainer, "createdb", "-U", "postgres", "-O", "weather_owner", scenario.foreignDatabase]);

  try {
    const refused = await runWrapper("verify-restore", scenario.indexedConfig);
    assert.notEqual(refused.code, 0);
    assert.match(refused.stderr, /preexisting restore candidate blocks rehearsal/u);
    const foreign = await runCommand("docker", [
      "exec",
      scenario.postgresContainer,
      "psql",
      "-U",
      "postgres",
      "-d",
      scenario.fixtureDatabase,
      "-Atc",
      `SELECT count(*) FROM pg_database WHERE datname = '${scenario.foreignDatabase}'`,
    ]);
    assert.equal(foreign.stdout.trim(), "1");
  } finally {
    await runCommand("docker", ["exec", scenario.postgresContainer, "dropdb", "-U", "postgres", "--if-exists", scenario.foreignDatabase]);
  }
});
