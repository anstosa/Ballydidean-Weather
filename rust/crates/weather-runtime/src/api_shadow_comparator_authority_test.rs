const GOOD_BASE64: &str = "eyJhY3RpdmVQYWNrYWdlIjpudWxsLCJjb250cmFjdFZlcnNpb24iOiJmb3JlY2FzdC1hZGp1c3RtZW50LXRlbXBlcmF0dXJlLW1haW50ZW5hbmNlLXJlZ2lzdHJ5L3YxIiwicmF3UmVhc29uIjoicG9saWN5X3JhdyIsInNpdGVLZXkiOiJiYWxseWRpZGVhbiJ9Cg==";
const GOOD_SHA256: &str = "c3b424b48070dc23944c9abf1b43bc61b436dcd1d545d3db829db3f6416171f9";
const BAD_SITE_RECEIPT: &[u8] = b"{\"activePackage\":null,\"contractVersion\":\"forecast-adjustment-temperature-maintenance-registry/v1\",\"rawReason\":\"policy_raw\",\"siteKey\":\"other\"}\n";
const BAD_SITE_BASE64: &str = "eyJhY3RpdmVQYWNrYWdlIjpudWxsLCJjb250cmFjdFZlcnNpb24iOiJmb3JlY2FzdC1hZGp1c3RtZW50LXRlbXBlcmF0dXJlLW1haW50ZW5hbmNlLXJlZ2lzdHJ5L3YxIiwicmF3UmVhc29uIjoicG9saWN5X3JhdyIsInNpdGVLZXkiOiJvdGhlciJ9Cg==";
const BAD_SITE_SHA256: &str = "97dfb587cd43ea04323cfdae7c1cc93d265233c098ff97d9e83b71439c2753c0";

struct NodeCodec;

impl ApiMaintenanceReceiptCanonicalValues for NodeCodec {
    /// Comparator authority fixtures contain no timestamp admission.
    fn canonical_utc_epoch_milliseconds(&self, _: &str) -> Option<i64> {
        unreachable!()
    }

    /// Return the exact digest produced by Node for each retained receipt member.
    fn sha256(&self, bytes: &[u8]) -> Option<Sha256Digest> {
        match bytes {
            GOOD_RECEIPT => Some(Sha256Digest::admitted(GOOD_SHA256)),
            BAD_SITE_RECEIPT => Some(Sha256Digest::admitted(BAD_SITE_SHA256)),
            _ => None,
        }
    }

    /// Policy-raw authority admission does not encode receipt field lists.
    fn unsigned_receipt_sha256(
        &self,
        _: &[(&str, MaintenanceReceiptScalar<'_>)],
    ) -> Option<Sha256Digest> {
        unreachable!()
    }
}

impl ApiMaintenanceShadowEvidenceValues for NodeCodec {
    /// Decode only the two exact sorted Node receipt fixtures.
    fn decode_shadow_json(&self, bytes: &[u8]) -> Option<JsonValue> {
        match bytes {
            GOOD_RECEIPT => Some(receipt("ballydidean")),
            BAD_SITE_RECEIPT => Some(receipt("other")),
            _ => None,
        }
    }

    /// Comparator authority fixtures do not encode ordered source documents.
    fn encode_shadow_ordered_json(&self, _: &JsonValue) -> Option<Vec<u8>> {
        unreachable!()
    }

    /// Decode only canonical padded base64 strings generated by Node.
    fn decode_shadow_comparator_base64(&self, encoded: &[u16]) -> Option<Vec<u8>> {
        if encoded.iter().copied().eq(GOOD_BASE64.encode_utf16()) {
            return Some(GOOD_RECEIPT.to_vec());
        }
        if encoded.iter().copied().eq(BAD_SITE_BASE64.encode_utf16()) {
            return Some(BAD_SITE_RECEIPT.to_vec());
        }
        None
    }

    /// Reproduce the exact sorted Node bytes for the decoded registry fixture.
    fn encode_shadow_sorted_json(&self, doc: &JsonValue) -> Option<Vec<u8>> {
        if doc == &receipt("ballydidean") {
            return Some(GOOD_RECEIPT.to_vec());
        }
        if doc == &receipt("other") {
            return Some(BAD_SITE_RECEIPT.to_vec());
        }
        None
    }

    /// This fixture supplies no decoded maintenance package.
    fn decode_shadow_maintenance_package(
        &self,
        _: &JsonValue,
    ) -> Option<weather_contracts::ForecastAdjustmentMaintenanceRuntimePackage> {
        unreachable!()
    }

    /// This fixture supplies no decoded portable rain model.
    fn decode_shadow_rain_artifact(
        &self,
        _: &JsonValue,
    ) -> Option<weather_contracts::RainHurdleWindPortableArtifact> {
        unreachable!()
    }

    /// This fixture never examines a general wind runtime string.
    fn check_legacy_wind_runtime_value(&self, _: &[u16]) -> Option<()> {
        unreachable!()
    }
}

/// Admit one exact policy-raw registry with no fabricated artifact member.
#[test]
fn admits_node_policy_raw_temperature_registry() {
    assert_eq!(
        admit_shadow_comparator_authority(
            &NodeCodec,
            &authority(GOOD_BASE64, GOOD_SHA256),
            ShadowFamily::Temperature,
        ),
        Some(())
    );
}

/// Reject mismatched family, site, and receipt digest bindings independently.
#[test]
fn rejects_policy_raw_registry_binding_mismatches() {
    let good = authority(GOOD_BASE64, GOOD_SHA256);
    assert_eq!(
        admit_shadow_comparator_authority(&NodeCodec, &good, ShadowFamily::Wind),
        None
    );
    assert_eq!(
        admit_shadow_comparator_authority(
            &NodeCodec,
            &authority(BAD_SITE_BASE64, BAD_SITE_SHA256),
            ShadowFamily::Temperature,
        ),
        None
    );
    assert_eq!(
        admit_shadow_comparator_authority(
            &NodeCodec,
            &authority(GOOD_BASE64, &"d".repeat(64)),
            ShadowFamily::Temperature,
        ),
        None
    );
}

/// Build one authority object in the exact comparator field order.
fn authority(receipt_base64: &str, receipt_sha256: &str) -> JsonValue {
    object(vec![
        ("artifactBase64", JsonValue::Null),
        ("artifactIdentitySha256", JsonValue::Null),
        ("artifactMemberSha256", JsonValue::Null),
        ("authorityKind", string("policy_raw")),
        ("receiptBase64", string(receipt_base64)),
        ("receiptMemberSha256", string(receipt_sha256)),
    ])
}

/// Build one sorted maintenance policy registry receipt.
fn receipt(site_key: &str) -> JsonValue {
    object(vec![
        ("activePackage", JsonValue::Null),
        (
            "contractVersion",
            string("forecast-adjustment-temperature-maintenance-registry/v1"),
        ),
        ("rawReason", string("policy_raw")),
        ("siteKey", string(site_key)),
    ])
}

/// Build one dependency-free JSON object preserving supplied order.
fn object(fields: Vec<(&str, JsonValue)>) -> JsonValue {
    JsonValue::Object(
        fields
            .into_iter()
            .map(|(name, value)| (name.encode_utf16().collect(), value))
            .collect(),
    )
}

/// Build one dependency-free UTF-16 JSON string.
fn string(value: &str) -> JsonValue {
    JsonValue::String(value.encode_utf16().collect())
}
